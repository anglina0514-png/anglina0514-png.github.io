function lessonPageSet(id) {
  if (!state.completedLessonPages[id]) state.completedLessonPages[id] = new Set();
  return state.completedLessonPages[id];
}

function lessonProgress(lesson) {
  if (state.completedLessons.has(lesson.id)) return 100;
  const pages = lessonPageSet(lesson.id).size;
  const quiz = state.lessonQuizResults[lesson.id]?.complete ? lesson.quiz.length : 0;
  const total = lesson.chapters.length + lesson.quiz.length + (lesson.match ? 1 : 0);
  return Math.round(((pages + quiz) / total) * 100);
}

function lessonStepCounts(lesson) {
  const chapterCount = lesson.chapters.length;
  const matchCount = lesson.match ? 1 : 0;
  const quizCount = lesson.quiz.length;
  const settlementStep = chapterCount + matchCount + quizCount;
  return { chapterCount, matchCount, quizCount, settlementStep, totalSteps: settlementStep + 1 };
}

