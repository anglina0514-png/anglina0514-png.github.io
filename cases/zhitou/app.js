function createCloudBaseAdapter(app, auth, rdb) {
  return {
    name: "cloudbase",
    getProfile(userId) {
      return rdb.from("profiles").select("*").eq("id", userId).maybeSingle();
    },
    upsertProfile(profile) {
      return rdb.from("profiles").upsert(profile, { onConflict: "id" }).select("*").single();
    },
    getSnapshot(userId) {
      return rdb.from("learning_snapshots").select("snapshot").eq("user_id", userId).maybeSingle();
    },
    saveSnapshot(payload) {
      return rdb.from("learning_snapshots").upsert(payload, { onConflict: "user_id" });
    },
    async signUp(email, password, nickname) {
      if (typeof auth.signUp === "function") {
        const response = await auth.signUp({ email, password });
        const error = authResponseError(response);
        if (error) return { data: null, error };
        const verifyOtp = response?.data?.verifyOtp;
        if (typeof verifyOtp === "function") {
          return {
            data: {
              pending: true,
              email,
              nickname: nickname || email.split("@")[0],
              verifyOtp,
              messageId: response?.data?.messageId || response?.data?.verification_id || response?.data?.verificationId,
            },
            error: null,
          };
        }
        return resolveCloudBaseAuthUser(auth, response, { email, nickname: nickname || email.split("@")[0] });
      }
      if (typeof auth.signUpWithEmailAndPassword !== "function") {
        return { data: null, error: authResultError("当前 CloudBase SDK 不支持邮箱注册，请检查静态资源版本。") };
      }
      const loginState = await auth.signUpWithEmailAndPassword(email, password);
      return resolveCloudBaseAuthUser(auth, loginState, { email, nickname: nickname || email.split("@")[0] });
    },
    async verifySignUp(pending, token) {
      if (!pending?.verifyOtp) {
        return { data: null, error: authResultError("注册验证码状态已失效，请重新提交注册信息。") };
      }
      const response = await pending.verifyOtp({
        token,
        messageId: pending.messageId,
      });
      return resolveCloudBaseAuthUser(auth, response, { email: pending.email, nickname: pending.nickname });
    },
    async signIn(email, password) {
      if (typeof auth.signInWithPassword === "function") {
        const response = await auth.signInWithPassword({ username: email, password });
        return resolveCloudBaseAuthUser(auth, response, { email });
      }
      if (typeof auth.signInWithEmailAndPassword !== "function") {
        return { data: null, error: authResultError("当前 CloudBase SDK 不支持邮箱密码登录，请检查静态资源版本。") };
      }
      const loginState = await auth.signInWithEmailAndPassword(email, password);
      return resolveCloudBaseAuthUser(auth, loginState, { email });
    },
    async startOtpLogin(email) {
      if (typeof auth.signInWithOtp !== "function") {
        return { data: null, error: authResultError("当前 CloudBase SDK 不支持邮箱验证码登录。") };
      }
      const response = await auth.signInWithOtp({ email, options: { shouldCreateUser: false } });
      const error = authResponseError(response);
      if (error) return { data: null, error };
      const verifyOtp = response?.data?.verifyOtp;
      if (typeof verifyOtp !== "function") {
        return { data: null, error: authResultError("CloudBase 没有返回验证码验证入口，请检查邮箱验证码配置。") };
      }
      return {
        data: {
          pending: true,
          email,
          verifyOtp,
          messageId: response?.data?.messageId || response?.data?.verification_id || response?.data?.verificationId,
        },
        error: null,
      };
    },
    async verifyOtpLogin(pending, token) {
      if (!pending?.verifyOtp) {
        return { data: null, error: authResultError("登录验证码状态已失效，请重新发送验证码。") };
      }
      const response = await pending.verifyOtp({
        token,
        messageId: pending.messageId,
      });
      return resolveCloudBaseAuthUser(auth, response, { email: pending.email });
    },
    async startPasswordReset(email) {
      if (typeof auth.resetPasswordForEmail !== "function") {
        return { data: null, error: authResultError("当前 CloudBase SDK 不支持邮箱验证码重设密码。") };
      }
      const response = await auth.resetPasswordForEmail(email);
      const error = authResponseError(response);
      if (error) return { data: null, error };
      const updateUser = response?.data?.updateUser;
      if (typeof updateUser !== "function") {
        return { data: null, error: authResultError("CloudBase 没有返回密码重设入口，请检查邮箱验证码配置。") };
      }
      return {
        data: {
          pending: true,
          email,
          updateUser,
        },
        error: null,
      };
    },
    async confirmPasswordReset(pending, token, password) {
      if (!pending?.updateUser) {
        return { data: null, error: authResultError("重设密码状态已失效，请重新发送验证码。") };
      }
      const response = await pending.updateUser({ nonce: token, password });
      return resolveCloudBaseAuthUser(auth, response, { email: pending.email });
    },
    signOut() {
      return auth.signOut();
    },
    onAuthChange(callback) {
      if (typeof auth.onAuthStateChange === "function") {
        auth.onAuthStateChange((_event, session) => callback(session?.user ? normalizeCloudBaseUser(session.user) : null));
      } else if (typeof auth.onLoginStateChanged === "function") {
        auth.onLoginStateChanged((loginState) => callback(loginState?.user ? normalizeCloudBaseUser(loginState.user) : null));
      }
    },
  };
}

async function initAuth() {
  loadLocalSnapshot();
  try {
    const runtimeCloudbaseConfig = window.ZTX_CLOUDBASE_CONFIG || null;
    if (window.location.protocol === "file:" && !API_BASE && !runtimeCloudbaseConfig?.enabled) {
      state.authReady = true;
      state.authConfigError = "真实登录需要通过线上链接或本地服务访问。";
      render();
      return;
    }
    let config = runtimeCloudbaseConfig?.enabled ? { cloudbase: runtimeCloudbaseConfig } : {};
    if (!runtimeCloudbaseConfig?.enabled || !runtimeCloudbaseConfig?.accessKey) {
      const response = await fetch(apiPath("/api/config"), { cache: "no-store" });
      const remoteConfig = await response.json().catch(() => ({}));
      config = {
        ...remoteConfig,
        cloudbase: {
          ...(runtimeCloudbaseConfig || {}),
          ...(remoteConfig.cloudbase || {}),
        },
      };
    }
    const cloudbaseConfig = config.cloudbase || {};
    if (cloudbaseConfig.enabled) {
      if (!window.cloudbase?.init) {
        state.authReady = true;
        state.authConfigError = "CloudBase 客户端加载失败，请检查静态资源。";
        render();
        return;
      }
      cloudbaseClient = window.cloudbase.init({
        env: cloudbaseConfig.envId,
        region: cloudbaseConfig.region || "ap-shanghai",
        ...(cloudbaseConfig.accessKey ? { accessKey: cloudbaseConfig.accessKey } : {}),
        auth: {
          detectSessionInUrl: true,
        },
        persistence: "local",
      });
      cloudbaseAuth = typeof cloudbaseClient.auth === "function"
        ? cloudbaseClient.auth({ persistence: "local" })
        : cloudbaseClient.auth;
      cloudbaseRdb = cloudbaseClient.rdb();
      authAdapter = createCloudBaseAdapter(cloudbaseClient, cloudbaseAuth, cloudbaseRdb);
      state.authConfigReady = true;
      const sessionResult = typeof cloudbaseAuth.getSession === "function"
        ? await cloudbaseAuth.getSession()
        : null;
      const loginState = typeof cloudbaseAuth.getSession === "function"
        ? sessionResult?.data?.session || sessionResult?.data || sessionResult?.session || sessionResult
        : await cloudbaseAuth.getLoginState?.();
      const cloudbaseUser = (loginState?.user || sessionResult?.data?.user)
        ? normalizeCloudBaseUser(loginState?.user || sessionResult?.data?.user)
        : null;
      if (cloudbaseUser && !cloudbaseUser.isAnonymous) await applyAuthUser(cloudbaseUser, true);
      else {
        state.authReady = true;
        state.syncStatus = "local";
        state.syncMessage = "学习资料保存在本机浏览器，登录后可同步。";
        render();
      }
      authAdapter.onAuthChange(async (user) => {
        if (user && !user.isAnonymous) await applyAuthUser(user, true);
        else if (user?.isAnonymous && !state.authUser) {
          state.authReady = true;
          state.syncStatus = "local";
          state.syncMessage = "学习资料保存在本机浏览器，登录后可同步。";
          render();
        }
        else {
          const hadUser = Boolean(state.authUser);
          state.authUser = null;
          state.authProfile = null;
          state.pendingRegistration = null;
          if (hadUser) resetSavingsPlanState();
          state.syncStatus = "local";
          state.syncMessage = "已退出登录，后续进度保存在本机浏览器。";
          render();
        }
      });
      return;
    }
    state.authReady = true;
    state.authConfigError = "CloudBase 登录服务未配置，当前只能浏览公开内容。";
    render();
  } catch (error) {
    state.authReady = true;
    state.authConfigError = "CloudBase 登录配置读取失败，当前只能浏览公开内容。";
    state.syncMessage = error.message || state.authConfigError;
    render();
  }
}

async function applyAuthUser(user, mergeCloud) {
  state.authUser = user;
  state.authReady = true;
  state.authError = "";
  state.authNotice = "";
  state.pendingRegistration = null;
  state.pendingOtpLogin = null;
  state.pendingPasswordReset = null;
  state.authDraft.otp = "";
  state.authDraft.newPassword = "";
  let syncHadError = false;
  try {
    await ensureUserProfile(user);
  } catch (error) {
    syncHadError = true;
    console.warn("Profile sync failed", error);
  }
  try {
    if (mergeCloud) await loadSnapshot();
  } catch (error) {
    syncHadError = true;
    console.warn("Snapshot load failed", error);
  }
  await saveSnapshot("login");
  if (syncHadError && state.syncStatus !== "error") {
    state.syncStatus = "error";
    state.syncMessage = "已登录，但云端学习资料同步不完整，稍后可重试。";
    render();
  }
}

async function ensureUserProfile(user) {
  if (!authAdapter || !user) return;
  const fallbackName = user.email?.split("@")[0] || "知投学员";
  const { data } = await authAdapter.getProfile(user.id);
  if (data) {
    state.authProfile = data;
    return;
  }
  const profile = {
    id: user.id,
    nickname: user.user_metadata?.nickname || fallbackName,
    avatar_color: "#2260d6",
    learning_goal: "建立投资基础框架",
    updated_at: new Date().toISOString(),
  };
  const { data: inserted } = await authAdapter.upsertProfile(profile);
  state.authProfile = inserted || profile;
}

async function loadSnapshot() {
  if (!authAdapter || !state.authUser) return;
  const { data, error } = await authAdapter.getSnapshot(state.authUser.id);
  if (error) {
    state.syncStatus = "error";
    state.syncMessage = "云端画像读取失败，已保留本机进度。";
    return;
  }
  if (data?.snapshot) restoreSnapshot(data.snapshot, true);
}

