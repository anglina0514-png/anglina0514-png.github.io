function restoreSnapshot(snapshot, merge = false) {
  if (!snapshot || typeof snapshot !== "object") return;
  const canRestoreSavings = Boolean(state.authUser);
  const previousCompleted = merge ? new Set(state.completedLessons) : new Set();
  (snapshot.completedLessons || []).forEach((id) => previousCompleted.add(Number(id)));
  state.completedLessons = previousCompleted;

  const nextPages = merge ? { ...state.completedLessonPages } : {};
  Object.entries(snapshot.completedLessonPages || {}).forEach(([lessonId, pages]) => {
    const set = new Set(nextPages[lessonId] || []);
    (pages || []).forEach((page) => set.add(page));
    nextPages[lessonId] = set;
  });
  state.completedLessonPages = nextPages;

  state.lessonQuizResults = Object.fromEntries(Object.entries(snapshot.lessonQuizResults || {}).map(([lessonId, result]) => [
    lessonId,
    { ...result, seen: new Set(result.seen || []) },
  ]));
  if (merge) {
    state.assessed = state.assessed || Boolean(snapshot.assessed);
    state.quizScore = Math.max(state.quizScore || 0, snapshot.quizScore || 0);
    state.coins = Math.max(state.coins || 0, snapshot.coins || 0);
    state.masteredTerms = Math.max(state.masteredTerms || 0, snapshot.masteredTerms || 0);
    state.streak = Math.max(state.streak || 0, snapshot.streak || 0);
    state.mistakes = Math.max(state.mistakes || 0, snapshot.mistakes || 0);
  } else {
    state.assessed = Boolean(snapshot.assessed);
    state.quizIndex = snapshot.quizIndex || 0;
    state.quizScore = snapshot.quizScore || 0;
    state.coins = snapshot.coins ?? 130;
    state.masteredTerms = snapshot.masteredTerms || 0;
    state.streak = snapshot.streak || 0;
    state.mistakes = snapshot.mistakes || 0;
  }
  state.recommendedRoute = snapshot.recommendedRoute || state.recommendedRoute;
  state.activeCategory = snapshot.activeCategory || state.activeCategory;
  state.finalExamAnswers = snapshot.finalExamAnswers || state.finalExamAnswers || {};
  state.finalExamDone = Boolean(snapshot.finalExamDone || state.finalExamDone);
  state.termDone = Boolean(snapshot.termDone || state.termDone);
  state.recentQuestions = Array.from(new Set([...(state.recentQuestions || []), ...(snapshot.recentQuestions || [])])).slice(0, 8);
  if (canRestoreSavings && snapshot.savingsPlanForm && typeof snapshot.savingsPlanForm === "object") {
    const legacyRisk = !Object.prototype.hasOwnProperty.call(snapshot.savingsPlanForm, "riskDrawdown")
      ? legacyRiskAnswers(snapshot.savingsPlanForm.riskLevel)
      : {};
    state.savingsPlanForm = {
      ...defaultSavingsPlanForm,
      ...snapshot.savingsPlanForm,
      ...legacyRisk,
      assets: Array.isArray(snapshot.savingsPlanForm.assets) && snapshot.savingsPlanForm.assets.length
        ? snapshot.savingsPlanForm.assets
        : defaultSavingsPlanForm.assets,
    };
  }
  if (canRestoreSavings && snapshot.savingsPlanResult && typeof snapshot.savingsPlanResult === "object") {
    const restoredPlan = calculateSavingsPlan(state.savingsPlanForm);
    if (!restoredPlan.errors.length) {
      state.savingsPlanResult = restoredPlan;
      state.savingsPlanAnswer = sanitizeAIAnswer(snapshot.savingsPlanAnswer || "");
      state.savingsPlanStatus = snapshot.savingsPlanStatus === "error" ? "error" : state.savingsPlanAnswer ? "success" : "idle";
      state.savingsPlanError = "";
    }
  }
  if (canRestoreSavings && Array.isArray(snapshot.savingsCheckins)) {
    state.savingsCheckins = snapshot.savingsCheckins
      .filter((item) => item && item.date)
      .map((item) => ({
        date: `${item.date}`,
        spend: parsePlanAmount(item.spend),
        surplus: Number(item.surplus) || 0,
        saved: Math.max(0, Number(item.saved) || 0),
        achieved: Boolean(item.achieved),
        createdAt: item.createdAt || new Date().toISOString(),
      }))
      .slice(-120);
  }
}

