function renderRichParagraphs(text, highlights) {
  return String(text)
    .split(/\n+/)
    .map((paragraph) => paragraph.trim())
    .filter(Boolean)
    .map((paragraph) => `<p>${highlightText(paragraph, highlights)}</p>`)
    .join("");
}

function highlightText(text, words) {
  let result = text;
  words.forEach((word) => {
    if (!word) return;
    result = result.replaceAll(word, `<mark>${word}</mark>`);
  });
  return result;
}

