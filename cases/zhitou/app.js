function paragraphHighlights(text, story, slide) {
  const explicit = Array.isArray(slide.highlights) ? slide.highlights : [];
  const numbers = `${text}`.match(/\d[\d,.]*(?:%|％|年|亿美元|亿元|亿|万亿|个岗位|个|Q\d+)?/g) || [];
  return [...new Set([...explicit, ...(story.terms || []), ...numbers])]
    .map((item) => `${item}`.trim())
    .filter((item) => item.length >= 2)
    .slice(0, 12);
}

function highlightStoryText(text, highlights) {
  const cleanHighlights = highlights.filter(Boolean);
  if (!cleanHighlights.length) return escapeHtml(text);
  const pattern = new RegExp(`(${cleanHighlights.map(escapeRegExp).join("|")})`, "g");
  return `${text}`.split(pattern).map((part) => {
    if (!part) return "";
    return cleanHighlights.includes(part)
      ? `<strong class="story-highlight">${escapeHtml(part)}</strong>`
      : escapeHtml(part);
  }).join("");
}

function renderRichStoryBody(text, story, slide = {}) {
  const highlights = paragraphHighlights(text, story, slide);
  return `
    <div class="story-rich-body">
      ${`${text || ""}`.split(/\n{2,}/).filter(Boolean).map((paragraph) => {
        const lines = paragraph.split(/\n/).map((line) => line.trim()).filter(Boolean);
        const bulletLines = lines.filter((line) => /^[-•*]\s+/.test(line));
        if (bulletLines.length && bulletLines.length === lines.length) {
          return `<ul>${bulletLines.map((line) => `<li>${highlightStoryText(line.replace(/^[-•*]\s+/, ""), highlights)}</li>`).join("")}</ul>`;
        }
        return `<p>${highlightStoryText(paragraph, highlights)}</p>`;
      }).join("")}
    </div>
  `;
}

