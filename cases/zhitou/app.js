let activeRailDrag = null;
let suppressNextRailClick = false;
let railClickResetTimer = null;

function updateRailNudge(shell) {
  const rail = shell?.querySelector("[data-drag-rail]");
  const nudge = shell?.querySelector("[data-rail-nudge]");
  if (!rail || !nudge) return;
  const maxScroll = Math.max(0, rail.scrollWidth - rail.clientWidth);
  const atEnd = rail.scrollLeft >= maxScroll - 3;
  nudge.classList.toggle("is-hidden", maxScroll <= 3 || atEnd);
}

function updateRailNudges() {
  document.querySelectorAll("[data-rail-shell]").forEach(updateRailNudge);
}

function nudgeRail(button) {
  const shell = button.closest("[data-rail-shell]");
  const rail = shell?.querySelector("[data-drag-rail]");
  if (!rail) return;
  rail.scrollBy({ left: Math.max(rail.clientWidth * 0.72, 120), behavior: "smooth" });
  window.setTimeout(() => updateRailNudge(shell), 280);
}

function suppressGeneratedRailClick() {
  suppressNextRailClick = true;
  window.clearTimeout(railClickResetTimer);
  railClickResetTimer = window.setTimeout(() => {
    suppressNextRailClick = false;
  }, 120);
}

function clearGeneratedRailClickSuppression() {
  suppressNextRailClick = false;
  window.clearTimeout(railClickResetTimer);
  railClickResetTimer = null;
}

