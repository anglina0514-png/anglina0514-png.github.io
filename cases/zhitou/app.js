async function requestHttpAIAnswer(prompt, model = state.askModel) {
  const response = await fetch(apiPath("/api/ask"), {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ question: prompt, model }),
  });
  const payload = await response.json().catch(() => ({}));
  if (!response.ok) throw new Error(payload.error || "AI 接口请求失败。");
  return payload;
}

async function askAIQuestion(question) {
  const prompt = question.trim();
  if (!prompt) return;
  const requestId = Date.now();
  const preferHttpAI = window.ZTX_AI_TRANSPORT === "http";
  const cloudbaseRequired = Boolean(window.ZTX_CLOUDBASE_CONFIG?.enabled && !preferHttpAI);
  state.askRequestId = requestId;
  state.askQuestion = prompt;
  state.askAnswer = "";
  state.askError = "";
  state.askStatus = "loading";
  state.recentQuestions = [prompt, ...state.recentQuestions.filter((item) => item !== prompt)].slice(0, 8);
  scheduleSnapshotSave("question");
  render();
  try {
    if (window.location.protocol === "file:" && !API_BASE) {
      throw new Error("AI 问答需要通过本地服务访问：运行 node server.mjs 后打开 http://127.0.0.1:5177/#ask。");
    }
    if (!preferHttpAI && cloudbaseRequired) {
      if (!cloudbaseClient?.callFunction) {
        throw new Error(state.authConfigError || "AI 服务正在初始化，请稍后再试。");
      }
      await ensureCloudBaseFunctionAuth();
      const result = await cloudbaseClient.callFunction({
        name: "ask",
        data: { question: prompt, model: state.askModel },
      });
      const payload = typeof result?.result?.body === "string"
        ? JSON.parse(result.result.body)
        : result?.result || {};
      if (payload.error) throw new Error(payload.error);
      if (state.askRequestId !== requestId) return;
      state.askAnswer = sanitizeAIAnswer(payload.answer) || "AI 暂时没有返回内容。";
      state.askStatus = "success";
      render();
      return;
    }
    const payload = await requestHttpAIAnswer(prompt);
    if (state.askRequestId !== requestId) return;
    state.askAnswer = sanitizeAIAnswer(payload.answer) || "AI 暂时没有返回内容。";
    state.askStatus = "success";
  } catch (error) {
    if (state.askRequestId !== requestId) return;
    if (!preferHttpAI && /credentials not found/i.test(error?.message || "")) {
      try {
        const payload = await requestHttpAIAnswer(prompt);
        if (state.askRequestId !== requestId) return;
        state.askAnswer = sanitizeAIAnswer(payload.answer) || "AI 暂时没有返回内容。";
        state.askStatus = "success";
        render();
        return;
      } catch (fallbackError) {
        error = fallbackError;
      }
    }
    state.askError = readableError(error, "AI 接口暂时不可用，请稍后再试。");
    state.askStatus = "error";
  }
  render();
}

