function normalizePercentRows(rows) {
  const total = rows.reduce((sum, row) => sum + row.percent, 0) || 1;
  rows.forEach((row) => row.percent = Math.max(0, Math.round((row.percent / total) * 100)));
  const diff = 100 - rows.reduce((sum, row) => sum + row.percent, 0);
  if (rows.length) rows[0].percent += diff;
  return rows;
}

function riskProfileById(id) {
  return riskProfiles.find((profile) => profile.id === id) || riskProfiles[0];
}

function riskQuestionScore(options, value) {
  const index = options.indexOf(value);
  return index >= 0 ? index : 0;
}

function legacyRiskScore(level) {
  if (level === "均衡") return 4;
  if (level === "稳健") return 2;
  return 0;
}

function riskProfileRank(id) {
  return Math.max(0, riskProfiles.findIndex((profile) => profile.id === id));
}

function limitRiskProfile(profileId, maxProfileId) {
  return riskProfileRank(profileId) > riskProfileRank(maxProfileId) ? maxProfileId : profileId;
}

function deriveRiskProfile(form, targetMonths) {
  const hasNewRiskAnswers = Boolean(form.riskDrawdown && form.riskReaction && form.riskUrgency);
  const score = hasNewRiskAnswers
    ? riskQuestionScore(riskDrawdownOptions, form.riskDrawdown)
      + riskQuestionScore(riskReactionOptions, form.riskReaction)
      + riskQuestionScore(riskUrgencyOptions, form.riskUrgency)
    : legacyRiskScore(form.riskLevel);
  let profileId = score <= 1 ? "low" : score <= 3 ? "steady" : score <= 5 ? "balanced" : "high";
  const adjustments = [];

  if (form.emergencyFund === "还没有准备") {
    if (profileId !== "low") adjustments.push("应急资金还没有准备，先降到低风险稳收益，把安全垫放在第一位。");
    profileId = "low";
  } else if (form.emergencyFund === "1-3 个月生活费") {
    const nextProfile = limitRiskProfile(profileId, "steady");
    if (nextProfile !== profileId) adjustments.push("应急资金只有 1-3 个月生活费，先限制高波动资产比例。");
    profileId = nextProfile;
  }

  if (targetMonths <= 12) {
    const nextProfile = limitRiskProfile(profileId, "low");
    if (nextProfile !== profileId) adjustments.push("目标期限在 12 个月以内，资金使用时间较近，优先稳住流动性。");
    profileId = nextProfile;
  } else if (targetMonths <= 24) {
    const nextProfile = limitRiskProfile(profileId, "steady");
    if (nextProfile !== profileId) adjustments.push("目标期限在 24 个月以内，不适合使用高风险高波动方案冲目标。");
    profileId = nextProfile;
  }

  const profile = riskProfileById(profileId);
  return {
    ...profile,
    score,
    adjustments,
    questions: {
      drawdown: form.riskDrawdown || "按旧风险承受字段映射",
      reaction: form.riskReaction || "按旧风险承受字段映射",
      urgency: form.riskUrgency || "按旧风险承受字段映射",
    },
  };
}

function stockCapForProfile(form, profile) {
  if (form.stockStyle === "个股为主") return Math.min(profile.stockCap, 15);
  if (form.stockStyle === "ETF + 少量个股学习仓位") return Math.min(profile.stockCap, 25);
  return profile.stockCap;
}

function buildPlanAllocation(form, monthlyBase, riskProfile) {
  const selected = new Set(form.assets?.length ? form.assets : defaultSavingsPlanForm.assets);
  if (form.emergencyFund === "还没有准备" || form.emergencyFund === "1-3 个月生活费") selected.add("bank");
  if (!selected.has("bank") && !selected.has("bonds")) selected.add("bonds");

  const weights = riskProfile.weights;
  let rows = planAssetOptions
    .filter((asset) => selected.has(asset.id))
    .map((asset) => ({ ...asset, percent: weights[asset.id] || 1 }));
  rows = normalizePercentRows(rows);

  const stock = rows.find((row) => row.id === "stock");
  if (stock) {
    const cap = stockCapForProfile(form, riskProfile);
    if (stock.percent > cap && rows.length > 1) {
      const excess = stock.percent - cap;
      stock.percent = cap;
      const others = rows.filter((row) => row.id !== "stock");
      others.forEach((row, index) => row.percent += Math.floor(excess / others.length) + (index < excess % others.length ? 1 : 0));
    }
  }
  rows = normalizePercentRows(rows);
  return rows.map((row) => {
    const label = row.id === "stock"
      ? form.stockStyle === "个股为主" ? "股票：个股学习仓位"
        : form.stockStyle === "ETF + 少量个股学习仓位" ? "股票：ETF + 少量个股"
          : "股票：ETF 为主"
      : row.label;
    return {
      ...row,
      label,
      monthlyAmount: Math.round(monthlyBase * row.percent / 100),
    };
  });
}

function calculateSavingsPlan(form) {
  const currentSavings = parsePlanAmount(form.currentSavings);
  const monthlyIncome = parsePlanAmount(form.monthlyIncome);
  const monthlySave = parsePlanAmount(form.monthlySave);
  const dailyBasicExpense = parsePlanAmount(form.dailyBasicExpense);
  const targetAmount = parsePlanAmount(form.targetAmount);
  const targetMonths = Math.max(0, Math.round(parsePlanAmount(form.targetMonths)));
  const errors = [];
  if (!targetAmount) errors.push("请填写储蓄目标金额。");
  if (!targetMonths) errors.push("请填写目标期限（月）。");
  if (!monthlyIncome) errors.push("请填写月收入。");
  if (!monthlySave) errors.push("请填写每月可储蓄/投资金额。");
  if (!dailyBasicExpense) errors.push("请填写每日基础消费。");
  if (!form.assets?.length) errors.push("请至少选择一种想参与的资产。");
  if (errors.length) return { errors };

  const dailyIncome = monthlyIncome / 30;
  const remaining = Math.max(0, targetAmount - currentSavings);
  const monthlyRequired = targetMonths ? remaining / targetMonths : 0;
  const dailyRequired = monthlyRequired / 30;
  const yearlyRequired = monthlyRequired * 12;
  const monthlyGap = Math.max(0, monthlyRequired - monthlySave);
  const targetReached = remaining <= 0;
  const monthlyBase = targetReached ? monthlySave : Math.min(monthlySave, monthlyRequired || monthlySave);
  const riskProfile = deriveRiskProfile(form, targetMonths);
  return {
    errors: [],
    currentSavings,
    monthlyIncome,
    monthlySave,
    dailyBasicExpense,
    dailyIncome,
    targetAmount,
    targetMonths,
    remaining,
    monthlyRequired,
    dailyRequired,
    yearlyRequired,
    monthlyGap,
    targetReached,
    monthlyBase,
    riskProfile,
    allocation: buildPlanAllocation(form, monthlyBase, riskProfile),
  };
}

function todayKey() {
  const date = new Date();
  const offsetDate = new Date(date.getTime() - date.getTimezoneOffset() * 60000);
  return offsetDate.toISOString().slice(0, 10);
}

function formatShortDate(value) {
  const [, month, day] = `${value}`.split("-");
  return month && day ? `${Number(month)}月${Number(day)}日` : value;
}

function positiveCheckinTotal() {
  return state.savingsCheckins.reduce((sum, item) => sum + Math.max(0, Number(item.saved) || 0), 0);
}

function checkinSummary(result) {
  const checkinTotal = positiveCheckinTotal();
  const totalSaved = result.currentSavings + checkinTotal;
  const remaining = Math.max(0, result.targetAmount - totalSaved);
  const progress = result.targetAmount ? Math.min(100, Math.round((totalSaved / result.targetAmount) * 100)) : 0;
  const today = state.savingsCheckins.find((item) => item.date === todayKey());
  return { checkinTotal, totalSaved, remaining, progress, today };
}

function calculateDailyCheckin(spend, result) {
  const surplus = result.dailyIncome - spend;
  const saved = Math.max(0, surplus);
  const budgetDelta = result.dailyBasicExpense - spend;
  return {
    spend,
    surplus,
    saved,
    budgetDelta,
    achieved: saved >= result.dailyRequired,
  };
}

