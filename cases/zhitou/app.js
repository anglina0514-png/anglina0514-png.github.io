function finishLessonStep() {
  const lesson = lessons.find((item) => item.id === state.activeLessonId);
  const { chapterCount, matchCount, settlementStep } = lessonStepCounts(lesson);
  if (state.activeLessonStep < chapterCount) {
    const pages = lessonPageSet(lesson.id);
    if (!pages.has(state.activeLessonStep)) {
      pages.add(state.activeLessonStep);
      addCoins(5);
    }
  } else if (matchCount && state.activeLessonStep === chapterCount) {
    const pages = lessonPageSet(lesson.id);
    if (!pages.has("match")) {
      pages.add("match");
      addCoins(10);
    }
  }
  state.activeLessonStep = Math.min(state.activeLessonStep + 1, settlementStep);
  state.activeQuizChoice = null;
  state.quizFeedback = null;
  state.activeMatchChoice = null;
  state.matchFeedback = null;
  scheduleSnapshotSave("lesson");
  render();
}

function finishCourse() {
  const lesson = lessons.find((item) => item.id === state.activeLessonId);
  state.completedLessons.add(lesson.id);
  state.activeCategory = lesson.category;
  if (!state.awardedLessons.has(lesson.id)) {
    state.awardedLessons.add(lesson.id);
    addCoins(lesson.reward);
  }
  state.screen = "learn";
  scheduleSnapshotSave("course");
  render();
}

function bindEvents() {
  document.addEventListener("error", (event) => {
    const image = event.target;
    if (!(image instanceof HTMLImageElement)) return;
    const fallback = image.dataset.fallbackSrc;
    if (!fallback || image.dataset.fallbackActive === "true") return;
    image.dataset.fallbackActive = "true";
    image.src = fallback;
  }, true);

  document.addEventListener("click", (event) => {
    if (!suppressNextRailClick || !event.target.closest("[data-drag-rail]")) return;
    event.preventDefault();
    event.stopImmediatePropagation();
    clearGeneratedRailClickSuppression();
  }, true);

  document.addEventListener("click", (event) => {
    const railNudge = event.target.closest("[data-rail-nudge]");
    if (railNudge) {
      nudgeRail(railNudge);
      return;
    }

    if (event.target.closest("[data-auth-open]")) {
      showAuthSheet(state.authUser ? "profile" : "login");
      return;
    }

    const authMode = event.target.closest("[data-auth-mode]");
    if (authMode) {
      state.authMode = authMode.dataset.authMode;
      state.authError = "";
      state.authNotice = "";
      if (state.authMode !== "verify") {
        state.pendingRegistration = null;
        state.authDraft.otp = "";
      }
      if (state.authMode !== "otpVerify") state.pendingOtpLogin = null;
      if (state.authMode !== "resetVerify") {
        state.pendingPasswordReset = null;
        state.authDraft.newPassword = "";
      }
      return showAuthSheet(state.authMode);
    }

    if (event.target.closest("[data-auth-submit]")) {
      submitAuthForm();
      return;
    }

    if (event.target.closest("[data-auth-logout]")) {
      signOut();
      return;
    }

    if (event.target.closest("[data-close-auth]")) {
      hideStory();
      return;
    }

    const screenButton = event.target.closest("[data-screen]");
    if (screenButton) {
      if (event.target.closest(".auth-sheet")) hideStory();
      if (screenButton.dataset.screen === "opportunities") state.activeOpportunityId = null;
      return setScreen(screenButton.dataset.screen);
    }

    if (event.target.closest("[data-back]")) {
      if (state.screen === "opportunities" && state.activeOpportunityId) {
        state.activeOpportunityId = null;
        return render();
      }
      const target = ["templates", "routes", "plan"].includes(state.screen) ? "home" : "home";
      return setScreen(target);
    }

    if (event.target.closest("[data-exit-course]")) return setScreen("learn");
    if (event.target.closest("[data-flag-lesson]")) return;

    const quiz = event.target.closest("[data-quiz]");
    if (quiz) {
      const question = assessmentQuestions[state.quizIndex];
      const selected = Number(quiz.dataset.quiz);
      state.quizScore += question.scores[selected];
      if (question.route) state.recommendedRoute = question.route[selected];
      state.quizIndex += 1;
      if (state.quizIndex >= assessmentQuestions.length) state.assessed = true;
      scheduleSnapshotSave("assessment");
      return render();
    }

    if (event.target.closest("[data-restart-quiz]")) {
      state.assessed = false;
      state.quizIndex = 0;
      state.quizScore = 0;
      scheduleSnapshotSave("assessment");
      return render();
    }

    const category = event.target.closest("[data-category]");
    if (category) {
      state.activeCategory = category.dataset.category;
      return render();
    }

    const lessonButton = event.target.closest("[data-open-lesson]");
    if (lessonButton) return openLesson(lessonButton.dataset.openLesson);

    const opportunityButton = event.target.closest("[data-open-opportunity]");
    if (opportunityButton) {
      state.activeOpportunityId = opportunityButton.dataset.openOpportunity;
      state.screen = "opportunities";
      window.location.hash = "opportunities";
      return render();
    }

    const holdingLogic = event.target.closest("[data-holding-logic]");
    if (holdingLogic) return renderHoldingLogic(holdingLogic.dataset.profile, holdingLogic.dataset.holdingLogic);

    if (event.target.closest("[data-next-lesson-step]")) return finishLessonStep();

    const answer = event.target.closest("[data-reader-answer]");
    if (answer) {
      const selected = Number(answer.dataset.readerAnswer);
      state.activeQuizChoice = selected;
      state.quizFeedback = null;
      return render();
    }

    const submitAnswer = event.target.closest("[data-submit-reader-answer]");
    if (submitAnswer && state.activeQuizChoice !== null) {
      const lesson = lessons.find((item) => item.id === state.activeLessonId);
      const { chapterCount, matchCount } = lessonStepCounts(lesson);
      const quizIndex = state.activeLessonStep - chapterCount - matchCount;
      const quiz = lesson.quiz[quizIndex];
      const selected = state.activeQuizChoice;
      const correct = selected === quiz.answerIndex;
      state.quizFeedback = correct ? quiz.correctText : quiz.wrongText;
      if (!state.lessonQuizResults[lesson.id]) state.lessonQuizResults[lesson.id] = { correct: 0, total: lesson.quiz.length, complete: false, seen: new Set() };
      const seenKey = `q${quizIndex}`;
      if (!state.lessonQuizResults[lesson.id].seen.has(seenKey)) {
        state.lessonQuizResults[lesson.id].seen.add(seenKey);
        if (correct) state.lessonQuizResults[lesson.id].correct += 1;
        else state.mistakes += 1;
      }
      if (quizIndex === lesson.quiz.length - 1) state.lessonQuizResults[lesson.id].complete = true;
      scheduleSnapshotSave("quiz");
      return render();
    }

    if (event.target.closest("[data-retry-answer]")) {
      state.activeQuizChoice = null;
      state.quizFeedback = null;
      state.matchFeedback = null;
      return render();
    }

    const removeMatch = event.target.closest("[data-remove-match]");
    if (removeMatch) {
      const lessonId = state.activeLessonId;
      const slot = Number(removeMatch.dataset.removeMatch);
      const current = { ...(state.matchSelections[lessonId] || {}) };
      delete current[slot];
      state.matchSelections[lessonId] = current;
      state.matchFeedback = null;
      return render();
    }

    const selectMatch = event.target.closest("[data-select-match-answer]");
    if (selectMatch) {
      state.activeMatchChoice = Number(selectMatch.dataset.selectMatchAnswer);
      state.matchFeedback = null;
      return render();
    }

    const dropSlot = event.target.closest("[data-drop-slot]");
    if (dropSlot && state.activeMatchChoice !== null) {
      const lessonId = Number(dropSlot.dataset.dropMatch);
      const slot = Number(dropSlot.dataset.dropSlot);
      const current = { ...(state.matchSelections[lessonId] || {}) };
      current[slot] = state.activeMatchChoice;
      state.matchSelections[lessonId] = current;
      state.activeMatchChoice = null;
      state.matchFeedback = null;
      return render();
    }

    const submitMatch = event.target.closest("[data-submit-match]");
    if (submitMatch) {
      const lesson = lessons.find((item) => item.id === Number(submitMatch.dataset.submitMatch));
      const selections = state.matchSelections[lesson.id] || {};
      const correct = lesson.match.pairs.every((_, index) => selections[index] === index);
      state.matchFeedback = correct
        ? { correct: true, text: "配对正确。你已经把风险信号、费用或配置动作放回了对应解释里。" }
        : { correct: false, text: "有配对还不准确。先看关键词，再把解释放到对应概念：名称、费用、风险目标要一一对应。" };
      if (!correct) state.mistakes += 1;
      scheduleSnapshotSave("match");
      return render();
    }

    if (event.target.closest("[data-understood-answer]")) return finishLessonStep();
    if (event.target.closest("[data-finish-course]")) return finishCourse();

    const finalAnswer = event.target.closest("[data-final-answer]");
    if (finalAnswer) {
      const questions = finalExamQuestions();
      const q = questions[state.finalExamIndex];
      const correct = Number(finalAnswer.dataset.finalAnswer) === q.answerIndex;
      state.finalExamAnswers[state.finalExamIndex] = correct;
      if (state.finalExamIndex >= questions.length - 1) {
        state.finalExamDone = true;
        if (!state.finalExamRewarded) {
          state.finalExamRewarded = true;
          addCoins(100);
        }
      } else state.finalExamIndex += 1;
      scheduleSnapshotSave("final");
      return render();
    }

    if (event.target.closest("[data-start-final]")) {
      if (state.completedLessons.size < TOTAL_LESSON_COUNT) return;
      state.screen = "finalExam";
      state.finalExamStarted = true;
      state.finalExamIndex = 0;
      state.finalExamAnswers = {};
      state.finalExamDone = false;
      return render();
    }

    if (event.target.closest("[data-reveal-term]") || event.target.closest(".flash-card")) {
      state.termRevealed = true;
      return render();
    }

    if (event.target.closest("[data-finish-term]") && state.termRevealed && !state.termDone) {
      state.termDone = true;
      state.masteredTerms = Math.max(1, state.masteredTerms + 1);
      state.streak = Math.max(1, state.streak + 1);
      addCoins(5);
      scheduleSnapshotSave("term");
      return render();
    }

    const queryTag = event.target.closest("[data-term-query]");
    if (queryTag) {
      const input = document.querySelector("[data-term-search]");
      input.value = queryTag.dataset.termQuery;
      document.getElementById("termResults").innerHTML = renderTermResults(input.value);
    }

    const askModel = event.target.closest("[data-ask-model]");
    if (askModel) {
      const modelId = askModel.dataset.askModel;
      if (askModels.some((model) => model.id === modelId)) {
        state.askModel = modelId;
        return render();
      }
    }

    const question = event.target.closest("[data-question]");
    if (question) {
      state.askDraft = question.dataset.question;
      askAIQuestion(question.dataset.question);
      return;
    }

    if (event.target.closest("[data-send-question]")) {
      const input = document.querySelector("[data-ask-input]");
      askAIQuestion(input.value.trim());
      return;
    }

    if (event.target.closest("[data-reset-local-experience]")) {
      resetLocalExperience();
      return;
    }

    if (event.target.closest("[data-generate-plan]")) {
      generateSavingsPlan();
      return;
    }

    if (event.target.closest("[data-submit-checkin]")) {
      submitSavingsCheckin();
      return;
    }

    const template = event.target.closest("[data-template]");
    if (template) {
      state.activeTemplate = Number(template.dataset.template);
      return render();
    }

    const story = event.target.closest("[data-story]");
    if (story) {
      state.storyIndex = Number(story.dataset.story);
      state.storySlide = 0;
      return renderStory();
    }

    if (event.target.closest("[data-close-story]") || event.target.closest("[data-close-logic]") || event.target.classList.contains("logic-sheet-backdrop")) return hideStory();

    if (event.target.closest("[data-next-story]")) {
      const max = stories[state.storyIndex].slides.length;
      state.storySlide = state.storySlide >= max ? 0 : state.storySlide + 1;
      return renderStory();
    }

    const storyVote = event.target.closest("[data-story-vote]");
    if (storyVote) {
      state.storyVotes[state.storyIndex] = Number(storyVote.dataset.storyVote);
      return renderStory();
    }

    const storyLearn = event.target.closest("[data-story-learn]");
    if (storyLearn) {
      if (state.storySlide >= stories[state.storyIndex].slides.length && state.storyVotes[state.storyIndex] === undefined) return;
      hideStory();
      return openLesson(storyLearn.dataset.storyLearn);
    }
  });

  document.addEventListener("input", (event) => {
    if (event.target.matches("[data-term-search]")) {
      document.getElementById("termResults").innerHTML = renderTermResults(event.target.value);
    }

    if (event.target.matches("[data-ask-input]")) {
      state.askDraft = event.target.value;
      const sendButton = document.querySelector("[data-send-question]");
      if (sendButton) sendButton.disabled = !state.askDraft.trim();
    }

    if (event.target.matches("[data-spending-input]")) {
      state.spendingDraft = event.target.value;
    }

    const planInput = event.target.closest("[data-plan-input]");
    if (planInput) {
      state.savingsPlanForm[planInput.dataset.planInput] = planInput.value;
      state.savingsPlanStatus = "idle";
      state.savingsPlanError = "";
      state.savingsPlanResult = null;
      state.savingsPlanAnswer = "";
      scheduleSnapshotSave("savings-plan-form");
    }

    const planAsset = event.target.closest("[data-plan-asset]");
    if (planAsset) {
      const assetId = planAsset.dataset.planAsset;
      const assets = new Set(state.savingsPlanForm.assets || []);
      if (planAsset.checked) assets.add(assetId);
      else assets.delete(assetId);
      state.savingsPlanForm.assets = Array.from(assets);
      state.savingsPlanStatus = "idle";
      state.savingsPlanError = "";
      state.savingsPlanResult = null;
      state.savingsPlanAnswer = "";
      scheduleSnapshotSave("savings-plan-assets");
      render();
    }

    if (event.target.matches("[data-lesson-search]")) {
      const keyword = event.target.value.trim().toLowerCase();
      document.querySelectorAll("[data-open-lesson]").forEach((card) => {
        const text = card.textContent.toLowerCase();
        card.style.display = !keyword || text.includes(keyword) ? "" : "none";
      });
    }

    if (event.target.matches("[data-equity-slider]")) {
      const value = Number(event.target.value);
      const hint = value <= 30 ? "当前偏稳健：优先学习债券基金、货币基金和流动性。" : value <= 55 ? "当前偏均衡：建议学习宽基指数、再平衡和最大回撤。" : "当前波动较高：先完成投资防坑和高波动资产课程。";
      document.getElementById("templateHint").textContent = hint;
    }
  });

  document.addEventListener("pointerdown", (event) => {
    const rail = event.target.closest("[data-drag-rail]");
    if (!rail || (event.pointerType === "mouse" && event.button !== 0)) return;
    activeRailDrag = {
      rail,
      pointerId: event.pointerId,
      startX: event.clientX,
      startY: event.clientY,
      scrollLeft: rail.scrollLeft,
      moved: false,
      dragging: false,
    };
  });

  document.addEventListener("pointermove", (event) => {
    if (!activeRailDrag || activeRailDrag.pointerId !== event.pointerId) return;
    const dx = event.clientX - activeRailDrag.startX;
    const dy = event.clientY - activeRailDrag.startY;
    if (!activeRailDrag.dragging) {
      if (Math.abs(dx) < 6) return;
      if (Math.abs(dy) > Math.abs(dx)) {
        activeRailDrag = null;
        return;
      }
      activeRailDrag.dragging = true;
      activeRailDrag.rail.classList.add("is-dragging");
      try {
        activeRailDrag.rail.setPointerCapture?.(event.pointerId);
      } catch (error) {
        // Pointer capture can fail if Chrome has already retargeted the pointer.
      }
    }
    activeRailDrag.moved = true;
    activeRailDrag.rail.scrollLeft = activeRailDrag.scrollLeft - dx;
    updateRailNudge(activeRailDrag.rail.closest("[data-rail-shell]"));
    event.preventDefault();
  }, { passive: false });

  const finishRailDrag = (event) => {
    if (!activeRailDrag || activeRailDrag.pointerId !== event.pointerId) return;
    activeRailDrag.rail.classList.remove("is-dragging");
    if (activeRailDrag.dragging) {
      try {
        activeRailDrag.rail.releasePointerCapture?.(event.pointerId);
      } catch (error) {
        // The pointer may already be released when the cursor leaves Chrome.
      }
    }
    if (activeRailDrag.moved) suppressGeneratedRailClick();
    updateRailNudge(activeRailDrag.rail.closest("[data-rail-shell]"));
    activeRailDrag = null;
  };

  document.addEventListener("pointerup", finishRailDrag);
  document.addEventListener("pointercancel", finishRailDrag);
  window.addEventListener("blur", () => {
    if (!activeRailDrag) return;
    activeRailDrag.rail.classList.remove("is-dragging");
    updateRailNudge(activeRailDrag.rail.closest("[data-rail-shell]"));
    activeRailDrag = null;
  });

  document.addEventListener("scroll", (event) => {
    const rail = event.target.closest?.("[data-drag-rail]");
    if (rail) updateRailNudge(rail.closest("[data-rail-shell]"));
  }, true);

  document.addEventListener("dragstart", (event) => {
    const chip = event.target.closest("[data-drag-answer]");
    if (!chip) return;
    event.dataTransfer.setData("text/plain", chip.dataset.dragAnswer);
  });

  document.addEventListener("dragover", (event) => {
    if (!event.target.closest("[data-drop-slot]")) return;
    event.preventDefault();
  });

  document.addEventListener("drop", (event) => {
    const slotNode = event.target.closest("[data-drop-slot]");
    if (!slotNode) return;
    event.preventDefault();
    const answerIndex = Number(event.dataTransfer.getData("text/plain"));
    if (Number.isNaN(answerIndex)) return;
    const lessonId = Number(slotNode.dataset.dropMatch);
    const slot = Number(slotNode.dataset.dropSlot);
    const current = { ...(state.matchSelections[lessonId] || {}) };
    current[slot] = answerIndex;
    state.matchSelections[lessonId] = current;
    state.activeMatchChoice = null;
    state.matchFeedback = null;
    scheduleSnapshotSave("match");
    render();
  });

  window.addEventListener("hashchange", () => {
    const courseMatch = window.location.hash.match(/^#course-(\d+)(?:-step-(\d+))?$/);
    if (courseMatch) {
      state.screen = "course";
      state.activeLessonId = Number(courseMatch[1]);
      state.activeLessonStep = courseMatch[2] ? Number(courseMatch[2]) : 0;
      state.activeQuizChoice = null;
      state.quizFeedback = null;
      state.activeMatchChoice = null;
      state.matchFeedback = null;
      render();
      return;
    }
    const next = screenFromHash();
    if (next !== state.screen) {
      if (next !== "opportunities") state.activeOpportunityId = null;
      state.screen = next;
      render();
    }
  });
}

