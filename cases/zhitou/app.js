function playCoinSound() {
  try {
    const AudioContext = window.AudioContext || window.webkitAudioContext;
    if (!AudioContext) return;
    const context = new AudioContext();
    const gain = context.createGain();
    gain.gain.setValueAtTime(0.001, context.currentTime);
    gain.gain.exponentialRampToValueAtTime(0.18, context.currentTime + 0.02);
    gain.gain.exponentialRampToValueAtTime(0.001, context.currentTime + 0.22);
    gain.connect(context.destination);
    [880, 1320].forEach((frequency, index) => {
      const oscillator = context.createOscillator();
      oscillator.type = "triangle";
      oscillator.frequency.setValueAtTime(frequency, context.currentTime + index * 0.055);
      oscillator.connect(gain);
      oscillator.start(context.currentTime + index * 0.055);
      oscillator.stop(context.currentTime + 0.18 + index * 0.055);
    });
    window.setTimeout(() => context.close(), 360);
  } catch {
    // Audio can be blocked by browser policy or system settings.
  }
}

function submitSavingsCheckin() {
  if (!requirePlanLogin("完成每日打卡")) return;
  const result = state.savingsPlanResult || calculateSavingsPlan(state.savingsPlanForm);
  if (!result || result.errors?.length) return;
  const spend = parsePlanAmount(state.spendingDraft);
  if (!spend && `${state.spendingDraft}`.trim() !== "0") {
    state.savingsPlanError = "请填写今天花了多少。";
    render();
    return;
  }
  const computed = calculateDailyCheckin(spend, result);
  const date = todayKey();
  const record = {
    date,
    spend: computed.spend,
    surplus: Math.round(computed.surplus),
    saved: Math.round(computed.saved),
    achieved: computed.achieved,
    createdAt: new Date().toISOString(),
  };
  const existingIndex = state.savingsCheckins.findIndex((item) => item.date === date);
  if (existingIndex >= 0) state.savingsCheckins[existingIndex] = record;
  else state.savingsCheckins = [...state.savingsCheckins, record].slice(-120);
  state.spendingDraft = "";
  state.savingsPlanResult = result;
  state.savingsPlanError = "";
  scheduleSnapshotSave("savings-checkin");
  showMoneyEffect(record.saved);
  render();
}

