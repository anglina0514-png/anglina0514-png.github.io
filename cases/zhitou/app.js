function escapeRegExp(value) {
  return `${value}`.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function storyStaticImage(image) {
  return image || "story-worldcup.png";
}

function storyOptimizedImage(image, variant = "hero") {
  const source = storyStaticImage(image);
  return source.replace(/\.png$/i, `.${variant}.webp`);
}

function storyPageImage(story, slideIndex) {
  if (slideIndex >= story.slides.length) return story.pollImage;
  return story.slides[slideIndex]?.image || story.image;
}

const prefetchedStoryImages = new Set();

function prefetchStoryHero(image) {
  const href = `${ASSET}${storyOptimizedImage(image, "hero")}`;
  if (prefetchedStoryImages.has(href)) return;
  prefetchedStoryImages.add(href);
  const link = document.createElement("link");
  link.rel = "prefetch";
  link.as = "image";
  link.type = "image/webp";
  link.href = href;
  link.fetchPriority = "low";
  document.head.appendChild(link);
}

function scheduleStoryImagePrefetch(story, slideIndex) {
  const run = () => {
    const nextIndex = Math.min(slideIndex + 1, story.slides.length);
    if (nextIndex !== slideIndex) prefetchStoryHero(storyPageImage(story, nextIndex));
    prefetchStoryHero(story.pollImage);
  };
  if ("requestIdleCallback" in window) {
    window.requestIdleCallback(run, { timeout: 900 });
  } else {
    window.setTimeout(run, 220);
  }
}

