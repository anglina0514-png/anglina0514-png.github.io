async function resolveCloudBaseAuthUser(auth, response, fallback = {}) {
  const responseError = authResponseError(response);
  if (responseError) return { data: { user: null, session: null }, error: responseError };

  let session = response?.data?.session || response?.session || response;
  let rawUser = response?.data?.user || session?.user || response?.user || null;

  if (!rawUser && typeof auth.getSession === "function") {
    const sessionResponse = await auth.getSession();
    const sessionError = authResponseError(sessionResponse);
    if (sessionError) return { data: { user: null, session: null }, error: sessionError };
    session = sessionResponse?.data?.session || sessionResponse?.session || session;
    rawUser = sessionResponse?.data?.user || session?.user || rawUser;
  }

  if (!rawUser && typeof auth.getSession !== "function" && typeof auth.getLoginState === "function") {
    const loginState = await auth.getLoginState().catch(() => null);
    session = session || loginState;
    rawUser = loginState?.user || rawUser;
  }

  const user = normalizeCloudBaseUser(rawUser || {});
  if (!isUsableAuthUser(user)) {
    return {
      data: { user: null, session },
      error: authResultError("CloudBase 没有返回可用登录用户，请确认邮箱密码登录已开启并完成验证。"),
    };
  }

  if (!user.email && fallback.email) user.email = fallback.email;
  if (fallback.nickname) user.user_metadata.nickname = fallback.nickname;
  return { data: { user, session }, error: null };
}

function readableError(error, fallback) {
  if (error?.message) return error.message;
  if (error?.helpMessage) return error.helpMessage;
  if (error?.category) return error.category;
  if (error?.code) return error.code;
  if (error?.errMsg) return error.errMsg;
  if (error?.error_description) return error.error_description;
  if (error?.error) return typeof error.error === "string" ? error.error : readableError(error.error, fallback);
  try {
    const text = JSON.stringify(error);
    if (text && text !== "{}") return text;
  } catch {
    // Ignore unserializable SDK errors and use the fallback.
  }
  return fallback;
}

function readableAuthError(error, fallback = "CloudBase 登录失败，请稍后再试。") {
  const message = readableError(error, fallback);
  if (/publishable|access.?key|apikey|api key/i.test(message)) return "CloudBase Publishable Key 未配置，暂时无法使用登录。";
  if (/provider.*not.*enabled|not.*enabled|identity|login.*method|auth_method/i.test(message)) return "CloudBase 邮箱密码登录未开启，请在控制台开启普通登录后再试。";
  if (/not.*verified|unverified|inactive|activate|confirm/i.test(message)) return "账号还没有完成邮箱验证，请先回到注册邮件完成验证码验证。";
  if (/verification|verify|otp|captcha|code|验证码|校验码|expired/i.test(message)) return "验证码不正确或已过期，请检查邮箱验证码后再试。";
  if (/smtp|mail|email.*service|send.*mail|邮件/i.test(message)) return "CloudBase 邮箱验证码服务未配置或发送失败，请检查控制台邮件配置。";
  if (/password/i.test(message) && /6|length|short/i.test(message)) return "密码至少需要 6 位。";
  if (/email/i.test(message) && /invalid|format/i.test(message)) return "邮箱格式不正确，请检查后再试。";
  if (/already|exist|registered/i.test(message)) return "这个邮箱可能已经注册，请直接登录。";
  if (/user.*not.*found|not.*found|user_not_found|no.*user/i.test(message)) return "没有找到这个邮箱的账号；如果刚注册，请先完成邮箱验证码。";
  if (/invalid.*login|wrong|invalid.*credential|credentials|password|INVALID_CREDENTIALS/i.test(message)) return "邮箱或密码不正确；可以改用邮箱验证码登录，或用验证码重设密码。";
  if (/network|fetch|timeout/i.test(message)) return "网络连接不稳定，CloudBase 登录服务暂时不可用。";
  return message;
}

async function ensureCloudBaseFunctionAuth() {
  if (!cloudbaseAuth) return;
  const loginState = await cloudbaseAuth.getLoginState().catch(() => null);
  if (loginState?.user) return;
  const anonymousProvider = cloudbaseAuth.anonymousAuthProvider?.();
  if (anonymousProvider?.signIn) {
    await anonymousProvider.signIn();
    return;
  }
  if (cloudbaseAuth.signInAnonymously) {
    await cloudbaseAuth.signInAnonymously({});
  }
}

