async function completeAuthResult(result, modeOnError) {
  if (result.error) {
    state.authError = readableAuthError(result.error);
    return showAuthSheet(modeOnError, state.authError);
  }
  if (!result.data?.user) {
    state.authError = "CloudBase 没有返回登录用户，请稍后重试。";
    return showAuthSheet(modeOnError, state.authError);
  }
  try {
    await applyAuthUser(result.data.user, true);
    hideStory();
  } catch (error) {
    state.authError = `登录成功，但云端学习资料同步失败：${readableAuthError(error, "请稍后重试。")}`;
    return showAuthSheet(modeOnError, state.authError);
  }
}

async function submitAuthForm() {
  if (!authAdapter) {
    state.authError = state.authConfigError || "CloudBase 登录服务未配置。";
    state.authConfigReady = false;
    return showAuthSheet(state.authMode, state.authError);
  }
  state.authNotice = "";
  if (["verify", "otpVerify", "resetVerify"].includes(state.authMode)) {
    const otp = document.querySelector("[data-auth-otp]")?.value.trim();
    state.authDraft.otp = otp || "";
    if (!otp) {
      state.authError = "请填写邮箱验证码。";
      return showAuthSheet(state.authMode, state.authError);
    }
    if (state.authMode === "resetVerify") {
      const newPassword = document.querySelector("[data-auth-new-password]")?.value || "";
      state.authDraft.newPassword = newPassword;
      if (newPassword.length < 6) {
        state.authError = "新密码至少需要 6 位。";
        return showAuthSheet("resetVerify", state.authError);
      }
      let resetResult;
      try {
        resetResult = await authAdapter.confirmPasswordReset(state.pendingPasswordReset, otp, newPassword);
      } catch (error) {
        resetResult = { error };
      }
      return completeAuthResult(resetResult, "resetVerify");
    }

    let verified;
    try {
      verified = state.authMode === "otpVerify"
        ? await authAdapter.verifyOtpLogin(state.pendingOtpLogin, otp)
        : await authAdapter.verifySignUp(state.pendingRegistration, otp);
    } catch (error) {
      verified = { error };
    }
    return completeAuthResult(verified, state.authMode);
  }

  if (["otpLogin", "reset"].includes(state.authMode)) {
    const email = authEmailFromSheet();
    state.authDraft.email = email;
    if (!validateAuthEmail(email, state.authMode)) return;
    let result;
    try {
      result = state.authMode === "reset"
        ? await authAdapter.startPasswordReset(email)
        : await authAdapter.startOtpLogin(email);
    } catch (error) {
      result = { error };
    }
    if (result.error) {
      state.authError = readableAuthError(result.error, state.authMode === "reset" ? "重设密码验证码发送失败，请稍后再试。" : "登录验证码发送失败，请稍后再试。");
      return showAuthSheet(state.authMode, state.authError);
    }
    if (state.authMode === "reset") {
      state.pendingPasswordReset = {
        email,
        updateUser: result.data.updateUser,
      };
      state.authDraft.otp = "";
      state.authDraft.newPassword = "";
      state.authMode = "resetVerify";
      state.authNotice = "重设验证码已发送，请检查邮箱后输入验证码和新密码。";
      return showAuthSheet("resetVerify");
    }
    state.pendingOtpLogin = {
      email,
      verifyOtp: result.data.verifyOtp,
      messageId: result.data.messageId,
    };
    state.authDraft.otp = "";
    state.authMode = "otpVerify";
    state.authNotice = "登录验证码已发送，请检查邮箱后输入验证码。";
    return showAuthSheet("otpVerify");
  }
  const email = document.querySelector("[data-auth-email]")?.value.trim();
  const password = document.querySelector("[data-auth-password]")?.value;
  const nickname = document.querySelector("[data-auth-nickname]")?.value.trim();
  state.authDraft.email = email || "";
  state.authDraft.nickname = nickname || state.authDraft.nickname || "";
  if (!validateAuthEmail(email || "", state.authMode)) return;
  if (!email || !password) {
    state.authError = state.authMode === "register" ? "请填写邮箱和密码；昵称可以不填。" : "请填写邮箱和密码。";
    return showAuthSheet(state.authMode, state.authError);
  }
  if (password.length < 6) {
    state.authError = "密码至少需要 6 位。";
    return showAuthSheet(state.authMode, state.authError);
  }
  let result;
  try {
    result = state.authMode === "register"
      ? await authAdapter.signUp(email, password, nickname)
      : await authAdapter.signIn(email, password);
  } catch (error) {
    result = { error };
  }
  if (result.error) {
    state.authError = readableAuthError(result.error);
    return showAuthSheet(state.authMode, state.authError);
  }
  if (state.authMode === "register" && result.data?.pending) {
    state.pendingRegistration = {
      email: result.data.email,
      nickname: result.data.nickname,
      verifyOtp: result.data.verifyOtp,
      messageId: result.data.messageId,
    };
    state.authDraft.email = result.data.email || email;
    state.authDraft.nickname = result.data.nickname || nickname || "";
    state.authDraft.otp = "";
    state.authMode = "verify";
    state.authError = "";
    return showAuthSheet("verify");
  }
  return completeAuthResult(result, state.authMode);
}

